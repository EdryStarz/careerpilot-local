import argparse
import asyncio
import json
import getpass
from datetime import datetime, timedelta
from pathlib import Path
from zoneinfo import ZoneInfo
import yaml
from .profile import Profile
from .ledger import Ledger

def init(path):
    path = Path(path)
    if path.exists():
        raise ValueError('Profile already exists; edit it yourself rather than overwriting')
    name = input('Your full name: ').strip()
    first = input('First name for application forms: ').strip()
    last = input('Last name for application forms: ').strip()
    email = input('Application email: ').strip()
    location = input('City, country: ').strip()
    country = input('Country name/code for location restrictions (e.g. DE): ').strip()
    cv = str(Path(input('Full path to your CV (.txt/.md/.docx/.pdf): ').strip().strip('"')).resolve())
    roles = [x.strip() for x in input('Target role regexes, separated by semicolons: ').split(';') if x.strip()]
    portfolio = input('Public portfolio URL (optional): ').strip()
    data = {'name':name,'first_name':first,'last_name':last,'email':email,'location':location,'country':country,'cv_path':cv,'resume_path':cv,
        'website':portfolio,'target_patterns':roles,'sources':['remotive','remoteok','wwr','himalayas'],
        'telegram_channels':[],'ats_boards':[],'answers':[],'portfolios':[],
        'enable_applications':False,'telegram_outreach_enabled':False,'hh_enabled':False,
        'min_score':85,'max_daily_applications':5,'max_review_per_run':20,'seconds_between_applications':60,
        'timezone':'UTC','daily_time':'01:30','filters':{'location_allow':'worldwide|global remote|work from anywhere',
        'exclude':'US.only|U\\.?S\\.?[- ]based|LATAM.only','allow_unknown_salary':True}}
    # Files are generated by the user's local wizard, never copied into GitHub.
    path.write_text(yaml.safe_dump(data,allow_unicode=True,sort_keys=False),encoding='utf-8')
    env = path.parent / '.env'
    if not env.exists():
        token = getpass.getpass('Telegram bot token (optional, hidden): ')
        owner = input('Your Telegram numeric user ID (optional): ').strip()
        env.write_text('TG_BOT_TOKEN='+token+'\nTG_USER_ID='+owner+'\nOLLAMA_URL=http://127.0.0.1:11434/api/chat\nLLM_MODEL=qwen3:4b\nTG_API_ID=\nTG_API_HASH=\n',encoding='utf-8')
        env.chmod(0o600)
    print('Private profile created. Review filters and answers, run doctor, then dry-run. Sending is disabled.')

async def execute(args):
    from .pipeline import run
    from .sources import collect
    from .telegram import account, bot, followups
    from .model import local_json
    profile = Profile.load(args.profile)
    ledger = Ledger(profile.state/'applications.db')
    if args.command == 'doctor':
        schema = {'type':'object','properties':{'ok':{'type':'boolean'}},'required':['ok']}
        result = await local_json(profile,'Return JSON {"ok":true}.',{},schema)
        if result != {'ok':True}:
            raise ValueError('Local model sanity check failed')
        print('Profile, CV and local model ready. Live submissions have not been tested.')
    elif args.command == 'collect':
        jobs, errors = await collect(profile)
        (profile.state/'jobs.json').write_text(json.dumps({'jobs':jobs,'source_errors':errors},ensure_ascii=False,indent=2),encoding='utf-8')
        print('Collected',len(jobs),'jobs; source errors:',len(errors),'; none submitted')
    elif args.command == 'run':
        report = await run(profile,ledger,args.send)
        print(json.dumps({'statuses':[j.get('status') for j in report['jobs']],'source_errors':report['source_errors']},ensure_ascii=False))
    elif args.command == 'status':
        print(json.dumps(ledger.summary(),ensure_ascii=False,indent=2))
    elif args.command == 'bot':
        await bot(profile,ledger)
    elif args.command == 'telegram-login':
        client = await account(profile,login=True)
        await client.disconnect()
        print('Personal Telegram session stored in OS keyring; no session file published')
    elif args.command == 'followups':
        from .pipeline import process_lock
        with process_lock(profile):
            print(json.dumps(await followups(profile,ledger),ensure_ascii=False))
    elif args.command == 'schedule':
        zone = ZoneInfo(profile.data.get('timezone','UTC'))
        hour, minute = map(int,profile.data.get('daily_time','01:30').split(':'))
        while True:
            now = datetime.now(zone)
            next_ = now.replace(hour=hour,minute=minute,second=0,microsecond=0)
            if next_ <= now:
                next_ += timedelta(days=1)
            await asyncio.sleep((next_-now).total_seconds())
            try:
                await run(profile,ledger,args.send)
                if args.send and profile.data.get('telegram_followups_enabled'):
                    from .pipeline import process_lock
                    with process_lock(profile):
                        await followups(profile,ledger)
            except Exception as exc:
                print('Scheduled run stopped:',type(exc).__name__)

def main():
    from . import __version__
    parser = argparse.ArgumentParser(description='Local CV-based multi-source career assistant')
    parser.add_argument('--version',action='version',version='CareerPilot Local '+__version__)
    parser.add_argument('command',choices=['init','doctor','collect','run','status','bot','telegram-login','followups','schedule'])
    parser.add_argument('--profile',default='careerpilot.yaml')
    parser.add_argument('--send',action='store_true',help='Actually apply; also requires explicit enable_applications in your profile')
    args = parser.parse_args()
    if args.command == 'init':
        init(args.profile)
    else:
        asyncio.run(execute(args))

if __name__ == '__main__':
    main()
